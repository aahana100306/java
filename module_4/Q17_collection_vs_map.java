public class Q17_collection_vs_map {
    public static void main(String[] args) {

        System.out.println("Collection vs Map");
        System.out.println();

        System.out.println("Collection:");
        System.out.println("1. Stores individual elements.");
        System.out.println("2. Examples are List, Set and Queue.");
        System.out.println("3. Elements are accessed individually.");
        System.out.println();

        System.out.println("Map:");
        System.out.println("1. Stores key-value pairs.");
        System.out.println("2. Each key is associated with a value.");
        System.out.println("3. Examples are HashMap and TreeMap.");
        System.out.println("4. Values are accessed using keys.");
    }
}