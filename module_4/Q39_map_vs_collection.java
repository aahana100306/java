public class Q39_map_vs_collection {
    public static void main(String[] args) {

        System.out.println("Map Interface vs Collection");
        System.out.println();

        System.out.println("Map:");
        System.out.println("1. Map stores data as key-value pairs.");
        System.out.println("2. Each key is associated with a value.");
        System.out.println("3. Keys are unique.");
        System.out.println("4. Examples: HashMap, LinkedHashMap and TreeMap.");
        System.out.println();

        System.out.println("Collection:");
        System.out.println("1. Collection stores individual elements.");
        System.out.println("2. Examples: List, Set and Queue.");
        System.out.println("3. It does not store data as key-value pairs.");
    }
}
