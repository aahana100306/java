public class Q31_set_vs_list {
    public static void main(String[] args) {

        System.out.println("Set Interface vs List Interface");
        System.out.println();

        System.out.println("Set:");
        System.out.println("1. Set does not allow duplicate elements.");
        System.out.println("2. Set generally does not maintain index positions.");
        System.out.println("3. Examples: HashSet, LinkedHashSet and TreeSet.");
        System.out.println();

        System.out.println("List:");
        System.out.println("1. List allows duplicate elements.");
        System.out.println("2. List maintains elements using indexes.");
        System.out.println("3. List maintains insertion order.");
        System.out.println("4. Examples: ArrayList and LinkedList.");
    }
}