public class Q32_hashset_linkedhashset_treeset {
    public static void main(String[] args) {

        System.out.println("HashSet vs LinkedHashSet vs TreeSet");
        System.out.println();

        System.out.println("HashSet:");
        System.out.println("1. Does not allow duplicate elements.");
        System.out.println("2. Does not guarantee insertion order.");
        System.out.println();

        System.out.println("LinkedHashSet:");
        System.out.println("1. Does not allow duplicate elements.");
        System.out.println("2. Maintains insertion order.");
        System.out.println();

        System.out.println("TreeSet:");
        System.out.println("1. Does not allow duplicate elements.");
        System.out.println("2. Stores elements in sorted order.");
        System.out.println("3. Useful when sorted data is required.");
    }
}