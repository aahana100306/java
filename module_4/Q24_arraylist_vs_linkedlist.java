public class Q24_arraylist_vs_linkedlist {
    public static void main(String[] args) {

        System.out.println("ArrayList vs LinkedList");
        System.out.println();

        System.out.println("ArrayList:");
        System.out.println("1. Uses a dynamic array internally.");
        System.out.println("2. Fast access using an index.");
        System.out.println("3. Inserting or removing from the middle can be slower.");
        System.out.println("4. Best when frequent access is required.");
        System.out.println();

        System.out.println("LinkedList:");
        System.out.println("1. Uses linked nodes internally.");
        System.out.println("2. Inserting and removing elements is efficient.");
        System.out.println("3. Accessing an element by index is slower.");
        System.out.println("4. Useful when frequent insertion and deletion are required.");
    }
}