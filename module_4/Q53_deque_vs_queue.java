public class Q53_deque_vs_queue {
    public static void main(String[] args) {

        System.out.println("Deque vs Queue");
        System.out.println();

        System.out.println("Queue:");
        System.out.println("1. Queue normally adds elements at one end.");
        System.out.println("2. Elements are removed from the other end.");
        System.out.println("3. It generally follows FIFO.");
        System.out.println();

        System.out.println("Deque:");
        System.out.println("1. Deque means Double Ended Queue.");
        System.out.println("2. Elements can be added at both ends.");
        System.out.println("3. Elements can be removed from both ends.");
        System.out.println("4. It can work as both a queue and a stack.");
    }
}