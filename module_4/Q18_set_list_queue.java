public class Q18_set_list_queue {
    public static void main(String[] args) {

        System.out.println("Set vs List vs Queue");
        System.out.println();

        System.out.println("List:");
        System.out.println("1. Maintains order.");
        System.out.println("2. Allows duplicate elements.");
        System.out.println("3. Example: ArrayList.");
        System.out.println();

        System.out.println("Set:");
        System.out.println("1. Does not allow duplicate elements.");
        System.out.println("2. Example: HashSet.");
        System.out.println();

        System.out.println("Queue:");
        System.out.println("1. Used to process elements in order.");
        System.out.println("2. Usually follows FIFO.");
        System.out.println("3. Example: LinkedList.");
    }
}