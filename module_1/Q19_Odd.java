public class Q19_Odd {
    public static void main(String[] args) {
        for (int i = 1; i <= 10; i++) {
            if (i % 2 != 0) {
                System.out.println(i+" is an odd number");
            }
        else {
                System.out.println(i+" is an even number");
            }
        }
    }
}